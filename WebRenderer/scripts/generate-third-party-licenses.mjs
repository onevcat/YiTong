import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRendererDirectory = path.resolve(__dirname, "..");
const repositoryDirectory = path.resolve(webRendererDirectory, "..");
const lockFilePath = path.join(webRendererDirectory, "package-lock.json");
const outputPaths = [
  path.join(repositoryDirectory, "LICENSES", "WebRenderer-THIRD-PARTY-LICENSES.txt"),
  path.join(
    repositoryDirectory,
    "Sources",
    "YiTongWebAssets",
    "Resources",
    "WebRenderer-THIRD-PARTY-LICENSES.txt",
  ),
];

const lockFile = JSON.parse(readFileSync(lockFilePath, "utf8"));
const packages = Object.entries(lockFile.packages)
  .filter(([relativePath, metadata]) =>
    relativePath.includes("node_modules/") && metadata.dev !== true,
  )
  .map(([relativePath, metadata]) => loadPackage(relativePath, metadata))
  .sort((lhs, rhs) => {
    if (lhs.name === rhs.name) {
      return lhs.version < rhs.version ? -1 : lhs.version > rhs.version ? 1 : 0;
    }
    return lhs.name < rhs.name ? -1 : 1;
  });

const separator = "=".repeat(80);
const content = [
  "YiTong WebRenderer third-party licenses",
  "",
  "AUTO-GENERATED by WebRenderer/scripts/generate-third-party-licenses.mjs.",
  "Do not edit this file by hand; run `npm run licenses` instead.",
  "",
  `Source lockfile: WebRenderer/package-lock.json`,
  `Included non-development packages: ${packages.length}`,
  "",
  ...packages.flatMap((dependency) => [
    separator,
    `${dependency.name} ${dependency.version}`,
    `Declared license: ${dependency.license}`,
    `Source: ${dependency.source}`,
    `License source: ${dependency.licenseSource}`,
    "-".repeat(80),
    dependency.licenseText,
    "",
  ]),
].join("\n");

if (process.argv.includes("--check")) {
  const stalePaths = outputPaths.filter(
    (outputPath) => !existsSync(outputPath) || readFileSync(outputPath, "utf8") !== content,
  );
  if (stalePaths.length > 0) {
    console.error(
      "Third-party license bundle is stale. Run `npm run licenses` and commit the result.",
    );
    for (const stalePath of stalePaths) {
      console.error(`- ${stalePath}`);
    }
    process.exit(1);
  }
  console.log(
    `Verified ${packages.length} WebRenderer production dependency licenses in ${outputPaths.length} locations.`,
  );
} else {
  for (const outputPath of outputPaths) {
    writeFileSync(outputPath, content);
    console.log(`Wrote ${packages.length} production dependency licenses to ${outputPath}.`);
  }
}

function loadPackage(relativePath, lockMetadata) {
  const packageDirectory = path.join(webRendererDirectory, relativePath);
  const packageJSON = JSON.parse(
    readFileSync(path.join(packageDirectory, "package.json"), "utf8"),
  );
  const licenseFiles = readdirSync(packageDirectory)
    .filter((name) => /^(licen[cs]e|copying|notice)(\..*)?$/i.test(name))
    .sort();

  let licenseText;
  let licenseSource;
  if (licenseFiles.length > 0) {
    licenseText = licenseFiles
      .map((name) => readFileSync(path.join(packageDirectory, name), "utf8").trim())
      .join("\n\n");
    licenseSource = licenseFiles.join(", ");
  } else {
    ({ licenseText, licenseSource } = loadFallbackLicense(
      packageDirectory,
      packageJSON.license ?? lockMetadata.license,
    ));
  }

  return {
    name: packageJSON.name,
    version: packageJSON.version ?? lockMetadata.version,
    license: String(packageJSON.license ?? lockMetadata.license ?? "UNKNOWN"),
    source: packageSource(packageJSON),
    licenseSource,
    licenseText,
  };
}

function loadFallbackLicense(packageDirectory, declaredLicense) {
  const normalizedLicense = String(declaredLicense ?? "").toLowerCase();
  if (normalizedLicense === "apache-2.0") {
    return {
      licenseText: readFileSync(path.join(repositoryDirectory, "LICENSE"), "utf8").trim(),
      licenseSource: "repository LICENSE (identical Apache-2.0 terms)",
    };
  }

  const readmeName = readdirSync(packageDirectory).find((name) =>
    /^readme(\..*)?$/i.test(name),
  );
  if (normalizedLicense === "mit" && readmeName != null) {
    const readme = readFileSync(path.join(packageDirectory, readmeName), "utf8");
    const marker = readme.search(/^# MIT licen[cs]e\s*$/im);
    if (marker >= 0) {
      return {
        licenseText: readme.slice(marker).trim(),
        licenseSource: `${readmeName} MIT license section`,
      };
    }
  }

  throw new Error(
    `No distributable license text found for ${path.basename(packageDirectory)} (${declaredLicense})`,
  );
}

function packageSource(packageJSON) {
  if (typeof packageJSON.repository === "string") {
    return packageJSON.repository;
  }
  if (packageJSON.repository?.url != null) {
    return packageJSON.repository.url;
  }
  return packageJSON.homepage ?? `npm:${packageJSON.name}`;
}
